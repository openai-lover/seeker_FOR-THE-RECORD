String _insertCaptures(String template, RegExpMatch match) =>
    template.replaceAllMapped(
      RegExp(r'\{(\d+)\}'),
      (placeholder) => match.group(int.parse(placeholder.group(1)!) + 1) ?? '',
    );

String normalizeLegacyTemplate(String value) {
  for (final (pattern, template) in _legacyTemplates) {
    final match = pattern.firstMatch(value);
    if (match != null) return _insertCaptures(template, match);
  }
  return value;
}

String translateTemplate(String language, String value, int index) {
  for (final (pattern, template) in _messageTemplates) {
    final match = pattern.firstMatch(value);
    if (match == null) continue;
    var key = template;
    if (match.group(1) == '1') {
      if (key == '{0} pages') key = '{0} page';
      if (key == '{0} pages\n{1}') key = '{0} page\n{1}';
      if (key == '{0} moments of progress · {1}') {
        key = '{0} moment of progress · {1}';
      }
    }
    final translation = translatedCatalog[key];
    if (translation != null) return _insertCaptures(translation[index], match);
  }
  return value;
}
