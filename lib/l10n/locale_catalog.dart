String translateEnglish(String language, String english) {
  final index = translationLanguages.indexOf(language);
  if (index < 0) return englishCountText(english);
  final direct = translatedCatalog[english];
  if (direct != null) return direct[index];
  return translateTemplate(language, english, index);
}

// These patterns match complete interface messages, never arbitrary words inside
// a journal. Captures are inserted verbatim, including any user-written text.
String englishCountText(String value) {
  if (value == '1 pages') return '1 page';
  if (value.startsWith('1 pages\n')) {
    return '1 page\n${value.substring('1 pages\n'.length)}';
  }
  if (value.startsWith('1 moments of progress · ')) {
    return '1 moment of progress · ${value.substring('1 moments of progress · '.length)}';
  }
  return value;
}

